/**
 * Everything about installing and running the git hooks: the generated
 * dispatcher file, locating/chaining an existing `core.hooksPath`, and the
 * `hook <name>` handlers themselves (pre-commit/prepare-commit-msg/
 * post-commit/post-rewrite) with their `$GIT_DIR` state files.
 *
 * The `hook` handler is the one thing that runs inside someone's commit, so
 * it is written to fail open: a hard budget, one-line stderr warning, exit 0
 * whatever happens. See `commands/repo.ts` for `attributeCommit` and the
 * other selection/attribution plumbing this module builds on.
 */

