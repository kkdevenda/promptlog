// DEVIATION from DESIGN.md: `pre-commit` is in the set too. Staging files from
// prepare-commit-msg does NOT put them in the commit - git has already read
// the index by then - and DESIGN.md requires the records to land in the same
// commit, so the store write + `git add` happen in pre-commit and
// prepare-commit-msg only writes the trailers (re-doing the write when
// pre-commit was bypassed).
export const HOOK_NAMES: readonly string[] = [
  'pre-commit',
  'prepare-commit-msg',
  'post-commit',
  'post-rewrite',
];

/**
 * A generated hook file: a tiny Node script that hands off to
 * `promptlog dispatch <name>` in the same bundle (see `commands/dispatch.ts`
 * for the actual logic). Node, not `sh`, so hooks run wherever Node and git
 * run, including Git for Windows (which invokes a hook file through its
 * shebang). `chainDir` is the hooks directory core.hooksPath pointed at
 * before promptlog took it over, or '' when there was none - see
 * DESIGN.md "Hooks".
 *
 * Fails open, always (DESIGN.md rule): when `bakedPath` is missing - a moved
 * or uninstalled promptlog - a bare `require()` would throw and could abort
 * the commit, so this checks `fs.existsSync` first and falls back to
 * locating `promptlog` on PATH itself: scanning each PATH entry with
 * `fs.existsSync`, trying every `PATHEXT` suffix on win32 (a shim is usually
 * `promptlog.cmd`, not a bare `promptlog`) or the bare name elsewhere - then
 * spawning it WITHOUT a shell. A shell was tried first; on Windows, `cmd.exe`
 * resolving a missing command prints its own "not recognized" error and
 * exits 1 - a status indistinguishable from `promptlog` itself failing - and
 * status 1 aborts the commit, the exact thing this fallback exists to
 * prevent. Finding the binary ourselves means "not found" is known before
 * spawning anything, so that case can warn once and exit 0 instead. The one
 * trade-off: in the not-found case any chained third-party hook (husky,
 * lefthook, a previous core.hooksPath) is skipped along with promptlog's own
 * work, since `dispatch` - which does the chaining - never got to run.
 */
function hookBody(hookName: string, chainDir: string | null): string {
  return [
    '#!/usr/bin/env node',
    '// promptlog git hook dispatcher (generated by `promptlog init`; do not edit)',
    `const bakedPath = ${JSON.stringify(entryPoint())};`,
    `const hookName = ${JSON.stringify(hookName)};`,
    `const chainDir = ${JSON.stringify(chainDir || '')};`,
    "const fs = require('fs');",
    'if (fs.existsSync(bakedPath)) {',
    "  process.argv.splice(2, 0, 'dispatch', hookName, '--chain-dir', chainDir);",
    '  require(bakedPath);',
    '} else {',
    "  const path = require('path');",
    "  const exts = process.platform === 'win32' ? (process.env.PATHEXT || '.EXE;.CMD;.BAT').split(';') : [''];",
    "  const dirs = (process.env.PATH || '').split(path.delimiter);",
    '  const candidates = [];',
    "  for (const dir of dirs) for (const ext of exts) candidates.push(path.join(dir, 'promptlog' + ext));",
    '  const found = candidates.find((c) => fs.existsSync(c));',
    '  if (found) {',
    "    const { spawnSync } = require('child_process');",
    "    const args = ['dispatch', hookName, '--chain-dir', chainDir, ...process.argv.slice(2)];",
    "    const r = spawnSync(found, args, { stdio: 'inherit' });",
    '    process.exit(r.status == null ? 0 : r.status);',
    '  }',
    '  process.stderr.write(\'promptlog: hook skipped, \' + bakedPath + " is missing and no promptlog on PATH; run \\`promptlog init\\` again\\n");',
    '  process.exit(0);',
    '}',
    '',
  ].join('\n');
}

/** The marker every dispatcher we write carries (see hookBody() above). */
const DISPATCHER_MARKER = 'promptlog git hook dispatcher';

/** Does `dir/prepare-commit-msg` hold one of OUR dispatchers? */
export function holdsOurDispatchers(dir: string): boolean {
  try {
    return fs.readFileSync(path.join(dir, 'prepare-commit-msg'), 'utf8').includes(DISPATCHER_MARKER);
  } catch {
    return false;
  }
}

/**
 * The hooks directory git actually consults for `root`, as an absolute
 * path, or null when core.hooksPath is unset at every scope. `--path` makes
 * git expand a leading `~`; a relative value is relative to the worktree
 * top. `scope` narrows the lookup (`--global`) for `init --global`, which
 * must not mistake a repo's local setting for the user-wide one.
 */
export function effectiveHooksPath(
  root: string,
  { scope = null }: { scope?: string | null } = {},
): string | null {
  const args = ['config', ...(scope ? [scope] : []), '--path', '--get', 'core.hooksPath'];
  const r = git.git(args, { cwd: root });
  if (!r.ok) return null;
  const value = r.stdout.trim();
  if (!value) return null;
  if (path.isAbsolute(value)) return value;
  const top = git.git(['rev-parse', '--show-toplevel'], { cwd: root });
  return path.resolve(top.ok && top.stdout.trim() ? top.stdout.trim() : root, value);
}

/**
 * The PROMPTLOG_CHAIN_DIR baked into the dispatcher already in `dir`, or
 * null. Re-running `init` overwrites our own dispatchers, and by then
 * core.hooksPath already points at `dir` itself - the directory it replaced
 * is only known from what the first run baked in, so it is carried forward
 * or the previous hooks would silently stop running on the second `init`.
 */
export function bakedChainDir(dir: string): string | null {
  let body: string;
  try {
    body = fs.readFileSync(path.join(dir, 'prepare-commit-msg'), 'utf8');
  } catch {
    return null;
  }
  if (!body.includes(DISPATCHER_MARKER)) return null;
  // Current (Node, fail-open) format: `const chainDir = "<json string>";`.
  const current = /^const chainDir = (.+);\s*$/m.exec(body);
  if (current) {
    try {
      const value = JSON.parse(current[1] as string) as unknown;
      return typeof value === 'string' && value ? value : null;
    } catch {
      return null;
    }
  }
  // Previous (Node, pre-fail-open) format: `'--chain-dir', "<json string>"`
  // as the last argument on the `process.argv.splice(...)` line. Kept so an
  // un-reinitialized dispatcher from before this file's fail-open rewrite
  // still carries its chain forward.
  const js = /'--chain-dir', (.+)\);\s*$/m.exec(body);
  if (js) {
    try {
      const value = JSON.parse(js[1] as string) as unknown;
      return typeof value === 'string' && value ? value : null;
    } catch {
      return null;
    }
  }
  // Old (sh) format, kept so a repo is upgraded without losing its chain: an
  // un-reinitialized dispatcher from before the Node port.
  const sh = /^PROMPTLOG_CHAIN_DIR='(.*)'$/m.exec(body);
  if (!sh) return null;
  const value = (sh[1] as string).replace(/'\\''/g, "'"); // undo the old shQuote
  return value && value !== '__PROMPTLOG_CHAIN_DIR__' ? value : null;
}

/**
 * The absolute promptlog.js path baked into hook file `file` (the argument to
 * `require(...)` in the current Node format, or `PROMPTLOG_JS='...'` in the
 * old sh format), or null when `file` does not hold one of our dispatchers.
 * Used by `doctor` (Grok finding P2): a moved or uninstalled promptlog means
 * the hook file's own `require()` throws before it ever gets to run, so this
 * is the only way left to warn about it.
 */
export function bakedEntryPoint(file: string): string | null {
  let body: string;
  try {
    body = fs.readFileSync(file, 'utf8');
  } catch {
    return null;
  }
  if (!body.includes(DISPATCHER_MARKER)) return null;
  // Current (Node, fail-open) format: `const bakedPath = "<json string>";`.
  const current = /^const bakedPath = (.+);\s*$/m.exec(body);
  if (current) {
    try {
      const value = JSON.parse(current[1] as string) as unknown;
      return typeof value === 'string' && value ? value : null;
    } catch {
      return null;
    }
  }
  // Previous (Node, pre-fail-open) format: a bare `require("<json>");`.
  const js = /^require\((.+)\);\s*$/m.exec(body);
  if (js) {
    try {
      const value = JSON.parse(js[1] as string) as unknown;
      return typeof value === 'string' && value ? value : null;
    } catch {
      return null;
    }
  }
  const sh = /^PROMPTLOG_JS='(.*)'$/m.exec(body);
  if (!sh) return null;
  const value = (sh[1] as string).replace(/'\\''/g, "'"); // undo the old shQuote
  return value && value !== '__PROMPTLOG_JS__' ? value : null;
}

/** Same directory: resolved, `realpath`'d when it exists, case-folded on
 * win32 (`fsutil.canonicalPath`) - so a short 8.3 alias or a case
 * difference in one of the two never reads as a different directory. */
export function samePath(a: string, b: string): boolean {
  return canonicalPath(a) === canonicalPath(b);
}

/**
 * Write the four dispatchers into `dir`, baking in our own entry point and,
 * when `chainDir` is given, the hooks directory core.hooksPath pointed at
 * before promptlog took it over (the dispatcher chains to it).
 */
export function installHooks(
  dir: string,
  { renameExisting = false, chainDir = null }: { renameExisting?: boolean; chainDir?: string | null } = {},
): string[] {
  fs.mkdirSync(dir, { recursive: true });
  const installed: string[] = [];
  for (const name of HOOK_NAMES) {
    const body = hookBody(name, chainDir);
    const target = path.join(dir, name);
    if (renameExisting && fs.existsSync(target)) {
      let isOurs = false;
      try {
        // A distinctive marker, not just "promptlog": a user's hook can
        // legitimately mention the word (or sit in a path that does).
        isOurs = fs.readFileSync(target, 'utf8').includes(DISPATCHER_MARKER);
      } catch {
        isOurs = false;
      }
      // Ours: just overwrite it. Somebody else's (husky, pre-commit, a
      // hand-written hook): rotate it to the first free .legacy slot.
      // Deleting it because `.legacy` happens to be taken would destroy a
      // hook the user installed after us, which a re-run of `init` must
      // never do.
      if (!isOurs) {
        let legacy = `${target}.legacy`;
        for (let n = 1; fs.existsSync(legacy) && n <= 20; n += 1) {
          legacy = `${target}.legacy.${n}`;
        }
        if (!fs.existsSync(legacy)) {
          fs.renameSync(target, legacy);
          try {
            fs.chmodSync(legacy, 0o755);
          } catch {
            /* ignore */
          }
        }
      }
    }
    fs.writeFileSync(target, body, 'utf8');
    fs.chmodSync(target, 0o755);
    installed.push(target);
  }
  return installed;
}

